# ============================================================
#  install-shims.ps1 - 生成命令 shim
#  pip  -> uv pip <subcommand> --system
#  npm  -> pnpm
#  npx  -> pnpm dlx   (即 pnpx)
#  (python/py 由 pymanager 管理，不生成 shim)
#
#  用法: pwsh -File windows/install-shims.ps1 [-ShimDir D:\PATH]
# ============================================================
param(
    [string]$ShimDir = 'D:\PATH'
)

$ErrorActionPreference = 'Stop'

if (-not (Get-Command uv -ErrorAction SilentlyContinue)) {
    throw 'uv 未安装。请先: winget install astral-sh.uv 或 cargo install uv'
}

# 注意: python / py 由 pymanager (Python Install Manager, winget:
# Python.PythonInstallManager) 管理, 本脚本不生成 python shim。
# uv 仅用于工具链 (uvx / uv tool), 解释器归 pymanager。

New-Item -ItemType Directory -Force $ShimDir | Out-Null
if (-not ($ShimDir -in ($env:Path -split ';'))) {
    Write-Warning "$ShimDir 不在 PATH 中，正在添加到用户 PATH"
    $p = [Environment]::GetEnvironmentVariable('Path', 'User')
    [Environment]::SetEnvironmentVariable('Path', "$ShimDir;$p", 'User')
}

function Write-Shim([string]$Name, [string[]]$Lines) {
    # 统一写 CRLF，避免 cmd 解析问题
    $ext = if ($Name -like '*.ps1') { 'ps1' } else { 'cmd' }
    [IO.File]::WriteAllText((Join-Path $ShimDir $Name), ($Lines -join "`r`n") + "`r`n")
    Write-Host "  [shim] $ShimDir\$Name"
}

Write-Host "生成 shim 到 $ShimDir :"

# 注意: .cmd 内容必须 ASCII + CRLF (cmd 在 GBK 代码页下无法正确解析
# UTF-8 中文注释和 LF 行尾), 因此 .cmd 一律用英文注释。

# ---- pip -> uv pip <subcommand> --system ----
Write-Shim 'pip.cmd' @(
    '@echo off',
    ':: pip -> uv pip <subcommand> --system (generated by install-shims.ps1)',
    'uv pip %* --system'
)
Write-Shim 'pip.ps1' @(
    '# pip -> uv pip <subcommand> --system (install-shims.ps1 生成)',
    'uv pip @args --system',
    'exit $LASTEXITCODE'
)

# ---- npm -> pnpm ----
Write-Shim 'npm.cmd' @(
    '@echo off',
    ':: npm -> pnpm (generated by install-shims.ps1)',
    'pnpm %*'
)
Write-Shim 'npm.ps1' @(
    '# npm -> pnpm (install-shims.ps1 生成)',
    'pnpm @args',
    'exit $LASTEXITCODE'
)

# ---- npx -> pnpm dlx (即 pnpx) ----
Write-Shim 'npx.cmd' @(
    '@echo off',
    ':: npx -> pnpm dlx (generated by install-shims.ps1)',
    'pnpm dlx %*'
)
Write-Shim 'npx.ps1' @(
    '# npx -> pnpm dlx (install-shims.ps1 生成)',
    'pnpm dlx @args',
    'exit $LASTEXITCODE'
)

Write-Host "完成。python/py 由 pymanager 管理。"
